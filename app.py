def run_wing_2():
    st.markdown("#### 📊 Калькулятор замера осевого люфта шпинделя:")
    col1, col2 = st.columns(2)
    with col1: size_A = st.number_input("Размер А (на весу), мм", min_value=0.0, value=15.0, step=0.1)
    with col2: size_B = st.number_input("Размер Б (на столе ротора), мм", min_value=0.0, value=10.0, step=0.1)
    fact_lift = round(size_A - size_B, 2)
    st.metric(label="Фактический расчетный люфт шпинделя (Δh):", value=f"{fact_lift} мм")
    passport_limit = st.number_input("Паспортный лимит износа опор по Руководству, мм", min_value=0.0, value=4.5, step=0.1)
    error_excluded = st.checkbox("Исключена ли ошибка измерений и перекосы измерительной рулетки?")
    if error_excluded:
        if fact_lift > passport_limit:
            st.error("🛑 ВЕРДИКТ [ДА]: СПУСК В СКВАЖИНУ ЗАПРЕЩЕН! Критический износ подшипников ВЗД. Оформить Акт износа, готовить резерв.")
        else:
            st.success(f"🟢 ВЕРДИКТ [НЕТ]: ЛЮФТ В НОРМЕ. ДВИГАТЕЛЬ ДОПУЩЕН К СПУСКУ. Зазор в пределах паспорта ({passport_limit} мм).")
    else:
        st.warning("⚠️ ПОГРЕШНОСТЬ ЗАМЕРА: Вернитесь на Шаг 1. Перемерить заново, жестко контролируя вертикальность рулетки.")

