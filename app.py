# ИСПРАВЛЕНО: АБСОЛЮТНО ПЛОСКОЕ ГЛАВНОЕ МЕНЮ БЕЗ ОПАСНЫХ ВЛОЖЕННОСТЕЙ
mode = st.selectbox(
    "📂 ВЫБЕРИТЕ РАЗДЕЛ РЕГЛАМЕНТА ДЛЯ РАБОТЫ:",
    ["1.1. Матрица рисков: Падение давления / Отсутствие пакета MWD",
     "1.2. Матрица рисков: Отклонение угла натяжения троса УМК",
     "1.3. Матрица рисков: Перекос осей резьбы или заклинивание замка",
     "1.4. Матрица рисков: Резонанс буровой вышки при тесте",
     "1.5. Веерный сценарий (Крыло 1): Заклинивание резьбы на мостках",
     "1.6. Веерный сценарий (Крыло 2): Анализ и расчет люфта шпинделя ВЗД",
     "1.7. Веерный сценарий (Крыло 3): Локализация течи при опрессовке",
     "1.8. Матрица рисков: Резкий вывод насосов на режим (Гидроудар)",
     "2.0. Калькулятор момента свинчивания ключа УМК (п. 5.1.1.8)"]
)

