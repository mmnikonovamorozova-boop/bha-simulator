# =========================================================================
# ПУНКТ 1.1: ТЕСТ ТЕЛЕМЕТРИИ
# =========================================================================
if "1.1." in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Нет пакета данных MWD / Падение давления на тесте.\nСледствие: Срыв этапа наземной поверки КНБК на мостках.")
    st.markdown("### 🛠️ Обязательные действия инженера ННБ:")
    st.info("Выполнить контроль уровня сигнала и оборотов генератора. Сделать контрольный поворот КНБК на 90° и 180° для оценки реакции отклонителя. Снять статический замер.")
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    mwd_ok = st.radio("Параметры каротажа стабильны и зенитный угол соответствует глубине опрессовки?", ["Выбрать...", "Да, параметры подтверждены", "Нет, сигналы нестабильны или отсутствуют"])
    if mwd_ok == "Да, параметры подтверждены":
        st.success("🍏 ВЕРДИКТ (ИСХОД ДА): СВЯЗЬ СТАБИЛЬНА. Спуск КНБК в скважину разрешен.")
    if mwd_ok == "Нет, сигналы нестабильны или отсутствуют":
        st.error("🚨 ВЕРДИКТ (ИСХОД НЕТ): СТОП ОПЕРАЦИЯ! Подъем телесистемы MWD для ревизии модулей.")

# =========================================================================
# ПУНКТ 1.2: ОПИСАНИЕ РИСКА УГЛА ТРОСА
# =========================================================================
if "1.2." in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Отклонение угла натяжения троса ключа УМК от 90°.\nСледствие: Скрытый недотяг/перетяг резьбового замка. Риск самоотворота КНБК в скважине.")
    st.markdown("### 🛠️ Условие регламента и развилка:")
    st.info("Инженер должен остановить затяжку, измерить плечо L и выставить трос строго перпендикулярно под углом 90°. Если это физически невозможно, необходимо запустить расчет поправки.")
    st.success("💡 ДЛЯ РАСЧЕТА ПОПРАВКИ: Перейдите в главное меню сверху и выберите раздел '2.0. Калькулятор момента свинчивания ключа УМК (п. 5.1.1.8)'.")

# =========================================================================
# ПУНКТ 1.3: ЗАКЛИНИВАНИЕ РЕЗЬБЫ В МАТРИЦЕ
# =========================================================================
if "1.3." in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Перекос осей резьбы или заклинивание замка на первых витках при наживлении.\nСледствие: Клиновидный размыв соединения, порча премиального замка КНБК.")
    st.markdown("### 🛠️ Обязательные действия инженера ННБ:")
    st.info("Немедленный стоп свинчивания! Осторожно открутить назад вручную. Полностью смыть смазку, обдуть сжатым воздухом. Осмотреть упорные поверхности.")
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    thread_ok = st.radio("Резьба идет плавно вручную, соосность СВП в норме?", ["Выбрать...", "Да, резьба закручивается плавно", "Нет, соединение по-прежнему клинит"])
    if thread_ok == "Да, резьба закручивается плавно":
        st.success("🍏 ВЕРДИКТ (ИСХОД ДА): Нанести смазку (2/3 муфта, 1/3 ниппель). ПРОДОЛЖИТЬ ШТАТНУЮ СБОРКУ КНБК.")
    if thread_ok == "Нет, соединение по-прежнему клинит":
        st.error("🚨 ВЕРДИКТ (ИСХОД НЕТ): КРИТИЧЕСКИЙ ДЕФЕКТ! ОТБРАКОВКА переводника/трубы. Составить Акт дефекта, вызвать резерв.")

# =========================================================================
# ПУНКТ 1.4: РЕЗОНАНС ВЫШКИ
# =========================================================================
if "1.4." in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Совпадение частоты пульсаций генератора импульсов с собственной частотой металлоконструкций буровой.\nСледствие: Резонанс вышки: опасная механическая вибрация, угроза разрушения блоков и верхнего привода СВП.")
    st.markdown("### 🛠️ Обязательные действия инженера ННБ:")
    st.info("Незамедлительно снизить расход буровых насосов до минимума для ослабления импульсов.")
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    resonance_stop = st.radio("Опасное раскачивание и вибрация конструкций буровой вышки прекратились?", ["Выбрать...", "Да, вышка стабилизировалась", "Нет, сильное раскачивание продолжается"])
    if resonance_stop == "Да, вышка стабилизировалась":
        st.success("🍏 ВЕРДИКТ (ИСХОД ДА): ТЕСТ НА ПОНИЖЕННОМ РАСХОДЕ (Q). Безопасный режим поверки осциллятора на поверхности.")
    if resonance_stop == "Нет, сильное раскачивание продолжается":
        st.error("🚨 ВЕРДИКТ (ИСХОД НЕТ): СТОП НАСОСОВ! Полный останов теста. Ревизия вышки и перерасчет параметров подачи.")

# =========================================================================
# ПУНКТ 1.5: ВЕЕР КРЫЛО 1 (РЕЗЬБА НА МОСТКАХ)
# =========================================================================
if "1.5." in mode:
    st.markdown("### 🛠️ ВЕЕРНЫЙ СЦЕНАРИЙ: ЗАКЛИНИВАНИЕ РЕЗЬБЫ НА МОСТКАХ")
    st.error("❌ ПЕРВИЧНОЕ ДЕЙСТВИЕ: СТОП вращение! Открутить вручную, смыть смазку, протереть замок.")
    defacts = st.selectbox("Результат внешнего осмотра поверхности замка КНБК:", ["Выбрать...", "Обнаружены мелкие задиры (Зачистка возможна)", "Обнаружены глубокие дефекты (Повреждения критические)", "Дефектов не обнаружено (Резьба чистая)"])
    if "Зачистка возможна" in defacts:
        st.success("🟢 РЕШЕНИЕ: Зачистить заусенцы надфилем вручную. Нанести смазку (2/3 в муфту, 1/3 ниппель). ПРОДОЛЖИТЬ СБОРКУ КНБК.")
    if "Повреждения критические" in defacts:
        st.error("🛑 ВЕРДИКТ: КРИТИЧЕСКИЙ ДЕФЕКТ! ОТБРАКОВКА трубы/переводника. Составить Акт дефекта, вызвать резерв.")
    if "Резьба чистая" in defacts:
        st.success("🟢 ВЕРДИКТ: Соосность инструмента восстановлена. Нанести герметизирующую смазку и ПРОДОЛЖИТЬ СБОРКУ КНБК.")

# =========================================================================
# ПУНКТ 1.6: ВЕЕР КРЫЛО 2 (ЛЮФТ ВЗД С КАЛЬКУЛЯТОРОМ) - АБСОЛЮТНО ИЗОЛИРОВАН
# =========================================================================
if "1.6." in mode:
    st.markdown("### 📊 ВЕЕРНЫЙ СЦЕНАРИЙ: АНАЛИЗ И РАСЧЕТ ОСЕВОГО ЛЮФТА ШПИНДЕЛЯ ВЗД")
    st.markdown("ℹ️ *Визуальное отсутствие хода штока генератора на воздухе НЕ является признаком отказа! Ход не обязателен. Выполните точный инструментальный замер:*")
    
    col1, col2 = st.columns(2)
    with col1:
        size_A = st.number_input("Размер А (на весу), мм", min_value=0.0, value=15.2, step=0.1)
    with col2:
        size_B = st.number_input("Размер Б (на столе ротора), мм", min_value=0.0, value=10.6, step=0.1)
    
    fact_lift = round(size_A - size_B, 2)
    st.metric(label="Фактический расчетный люфт шпинделя (Δh):", value=f"{fact_lift} мм")
    passport_limit = st.number_input("Паспортный лимит износа опор по Руководству, мм", min_value=0.0, value=4.5, step=0.1)
    
    st.markdown("---")
    error_excluded = st.checkbox("Гарантируете, что ошибка измерений полностью исключена?")
    if error_excluded:
        if fact_lift > passport_limit:
            st.error(f"🛑 ВЕРДИКТ: СПУСК В СКВАЖИНУ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕН! Износ опор подшипников ВЗД выше лимита ({fact_lift} мм > Предел {passport_limit} мм).")
        if fact_lift <= passport_limit:
            st.success(f"🟢 ВЕРДИКТ: ЛЮФТ В НОРМЕ. ДВИГАТЕЛЬ ДОПУЩЕН К СПУСКУ ({fact_lift} мм <= Норма {passport_limit} мм).")
    if not error_excluded:
        st.warning("⚠️ ПОГРЕШНОСТЬ ЗАМЕРА: Рекомендуется перемерить заново. После исключения погрешности поставьте галочку выше для вывода вердикта.")

# =========================================================================
