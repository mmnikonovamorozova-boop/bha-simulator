import streamlit as st
import math

# Настройка страницы (Широкий формат, как в калькуляторе УМК)
st.set_page_config(page_title="Инженерный пульт КНБК", layout="centered")

st.title("🎓 Комплексный тренажер инженера ННБ")
st.caption("Единая цифровая система сквозного контроля, расчета параметров и ликвидации осложнений при сборке КНБК")

# МЕНЮ ВЕРХНЕГО УРОВНЯ
main_mode = st.selectbox(
    "📂 ВЫБЕРИТЕ РАЗДЕЛ РЕГЛАМЕНТА ДЛЯ РАБОТЫ:",
    ["1. Ликвидация инцидентов и осложнений на мостках / опрессовке",
     "2. Калькулятор поправок момента свинчивания ключа УМК (п. 5.1.1.8)",
     "3. Расчет параметров плавного пуска насосов против гидроудара (п. 5.1.1.13)"]
)

st.markdown("---")

# =========================================================================
# РАЗДЕЛ 1: СИМУЛЯТОР ОСЛОЖНЕНИЙ (ВАШИ ТРИ ИНЦИДЕНТА)
# =========================================================================
if main_mode == "1. Ликвидация инцидентов и осложнений на мостках / опрессовке":
    
    incident_type = st.radio(
        "⚠️ ВЫБЕРИТЕ ТИП ВОЗНИКШЕГО ОСЛОЖНЕНИЯ:",
        ["Инцидент №1: Резьбовое соединение заклинило на первых витках", 
         "Инцидент №2: Замер осевого люфта ВЗД выше паспортного лимита",
         "Инцидент №3: Обнаружена течь при гидроиспытаниях (опрессовка на поверхности)"]
    )
    st.markdown("---")

    if "Инцидент №1" in incident_type:
        st.markdown("### 📋 Обязательные первичные действия инженера:")
        st.markdown("❌ **1. Немедленно остановить наживление / вращение инструмента!**")
        st.markdown("❌ **2. Осторожно открутить элемент назад вручную или цепным ключом (без рывков).**")
        st.markdown("❌ **3. Полностью смыть смазку, насухо протереть замок ветошью.**")
        
        st.markdown("---")
        st.markdown("### 🔍 Проверка факторов и дилемма:")
        defacts = st.selectbox("Есть ли видимые дефекты, задиры или трещины на резьбе?", ["Выбрать...", "Да, обнаружены дефекты", "Нет видимых дефектов"])
        
        if defacts == "Да, обнаружены дефекты":
            clean = st.radio("Глубина задиров допускает локальную зачистку?", ["Да, зачистка возможна", "Нет, повреждения слишком глубокие"])
            if clean == "Да, зачистка возможна":
                st.markdown("✨ **РЕШЕНИЕ:** Зачистить заусенцы надфилем/напильником. Проверить вертикальность соосности по СВП. Нанести герметизирующую смазку (2/3 муфта, 1/3 ниппель) и повторно наживить ВРУЧНУЮ.")
                st.markdown("🍏 **ВЕРДИКТ:** Осложнение ликвидировано. **ПРОДОЛЖИТЬ СБОРКУ КНБК.**")
            else:
                st.markdown("🚨 **ВЕРДИКТ: ЭЛЕМЕНТ КАТЕГОРИЧЕСКИ ЗАБРАКОВАН! Дальнейшая сборка запрещена.**")
                st.markdown("⚠️ **Обязательные действия:** Составить Акт дефекта, незамедлительно уведомить Координатора проекта.")
        elif defacts == "Нет видимых дефектов":
            st.markdown("✨ **РЕШЕНИЕ:** Проверить вертикальность и соосность по СВП / талевому блоку. Нанести герметизирующую смазку и повторно наживить элемент ВРУЧНУЮ.")
            st.markdown("🍏 **ВЕРДИКТ:** Соединение исправно. **ПРОДОЛЖИТЬ СБОРКУ КНБК.**")

    elif "Инцидент №2" in incident_type:
        st.markdown("### 📋 Обязательные первичные действия инженера:")
        st.markdown("ℹ️ **1. Выполнить повторный чистый замер по регламентированной формуле:** **Люфт = А (на весу) - Б (на столе)**.")
        st.markdown("ℹ️ **2. Проверить и исключить любые перекосы рулетки при измерениях.**")
        
        st.markdown("---")
        st.markdown("### 📊 Ввод параметров замера люфта шпинделя:")
        col1, col2 = st.columns(2)
        with col1: size_A = st.number_input("Размер А (на весу), мм", min_value=0.0, value=15.0, step=0.1)
        with col2: size_B = st.number_input("Размер Б (на столе ротора), мм", min_value=0.0, value=10.0, step=0.1)
            
        fact_lift = round(size_A - size_B, 2)
        st.metric(label="Фактический расчетный люфт шпинделя (Δh):", value=f"{fact_lift} мм")
        passport_limit = st.number_input("Паспортный лимит износа опор по Руководству по эксплуатации, мм", min_value=0.0, value=4.5, step=0.1)
        
        st.markdown("---")
        st.markdown("### 🔍 Проверка факторов и дилемма:")
        error_excluded = st.checkbox("Гарантируете, что ошибка измерений на буровой площадке полностью исключена?")
        
        if error_excluded:
            if fact_lift > passport_limit:
                st.markdown(f"🚨 **ВЕРДИКТ: СПУСК В СКВАЖИНУ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕН! Превышен лимит износа подшипников (Фактически {fact_lift} мм > Лимит {passport_limit} мм).**")
                st.markdown("⚠️ **Обязательные действия:** Известить Координатора, составить Акт износа, экстренно готовить резервный ВЗД.")
            else:
                st.markdown(f"🍏 **ВЕРДИКТ: ДВИГАТЕЛЬ ДОПУЩЕН К СПУСКУ. Расчетный люфт {fact_lift} мм в пределах паспортной нормы ({passport_limit} мм).**")
        else:
            st.markdown("📋 **РЕКОМЕНДАЦИЯ:** Вернитесь на Шаг 1. Перемерить заново, жестко контролируя вертикальность рулетки.")

    else:
        st.markdown("### 📋 Обязательные первичные действия инженера:")
        st.markdown("❌ **1. Немедленно дать команду остановить буровые насосы!**")
        st.markdown("❌ **2. Сбросить избыточное давление бурового раствора в манифольде до 0 атм.**")
        
        st.markdown("---")
        st.markdown("### 🔍 Локализация и анализ неисправности:")
        leak_location = st.selectbox("Где именно локализована течь раствора?", ["Выбрать...", "В резьбовом стыке (замок КНБК)", "Из корпуса ВЗД / из узла регулятора угла перекоса"])
        
        if leak_location == "В резьбовом стыке (замок КНБК)":
            under_torque = st.radio("Был ли допущен недотяг соединения по крутящему моменту ключа УМК?", ["Да, момент ниже паспортного", "Нет, момент затяжки в норме"])
            if under_torque == "Да, момент ниже паспортного":
                st.markdown("✨ **РЕШЕНИЕ:** Докрепить резьбовое соединение КНБК ключами УМК строго до верхнего паспортного предела.")
                st.markdown("🔄 **СЛЕДУЮЩИЙ ШАГ:** Выполнить повторный запуск буровых насосов и провести контроль герметичности.")
            else:
                st.markdown("🛠️ **РЕШЕНИЕ:** Раскрепить замок КНБК машинным ключом. Внимательно проверить торцы и упорные поверхности. Полностью обновить герметизирующую смазку.")
                st.markdown("🔄 **СЛЕДУЮЩИЙ ШАГ:** Повторно свинтить соединение, выполнить запуск насосов и контроль герметичности.")
        elif leak_location == "Из корпуса ВЗД / из узла регулятора угла перекоса":
            st.markdown("🚨 **ВЕРДИКТ: ДВИГАТЕЛЬ ВЗД КАТЕГОРИЧЕСКИ ЗАБРАКОВАН! Выявлена трещина корпуса или критический износ внутренних уплотнений. Эксплуатация запрещена.**")
            st.markdown("⚠️ **Обязательные действия:** Составить рекламационный акт, направить Координатору, готовить резервный ВЗД.")

# =========================================================================
# РАЗДЕЛ 2: КАЛЬКУЛЯТОР ПОПРАВОК КЛЮЧА УМК (СТРОКА №2 МАТРИЦЫ)
# =========================================================================
elif main_mode == "2. Калькулятор поправок момента свинчивания ключа УМК (п. 5.1.1.8)":
    st.markdown("### 📊 Расчет скрытой погрешности моментомера при перекосе троса натяжения")
    
    target_torque = st.number_input("Требуемый паспортный момент затяжки резьбового замка КНБК, кН·м", min_value=1.0, value=35.0, step=0.5)
    pull_angle = st.number_input("Фактический угол между натяжным тросом и телом ключа УМК, градусов", min_value=10, max_value=170, value=90, step=1)
    
    # Расчет скрытой погрешности из-за отклонения от перпендикуляра (плечо силы = L * sin(angle))
    radial_angle = math.radians(pull_angle)
    efficiency = math.sin(radial_angle)
    error_percent = round((1.0 - efficiency) * 100, 1)
    
    # Необходимое скорректированное усилие на приборе для достижения реального момента
    required_gauge_torque = round(target_torque / efficiency, 1)
    
    st.markdown("---")
    st.markdown("### 🔍 Результаты инженерного расчета:")
    
    if pull_angle == 90:
        st.success(f"🍏 Угол идеален (90°). Погрешность измерения крутящего момента отсутствует (0%). Выставляйте на приборе ровно **{target_torque} кН·м**.")
    else:
        st.error(f"🚨 ОБНАРУЖЕН ПЕРЕКОС ТРОСА! Скрытая потеря передаваемого момента составляет: **{error_percent}%**.")
        st.warning(f"📋 **ИНСТРУКЦИЯ И ПОПРАВКА К РЕГЛАМЕНТУ:**\\nЕсли вы выставите на приборе стандартные {target_torque} кН·м, замок останется недотянутым! Чтобы компенсировать перекос троса и затянуть резьбу правильно, **тяните ключ до показания {required_gauge_torque} кН·м** на моментомере.")

# =========================================================================
# РАЗДЕЛ 3: ЭТПЫ ПЛАВНОГО ПУСКА НАСОСОВ (СТРОКА №6 МАТРИЦЫ)
# =========================================================================
else:
    st.markdown("### 📊 Калькулятор безопасного ступенчатого вывода буровых насосов на режим")
    
    target_flow = st.number_input("Целевой плановый расход промывочной жидкости по расчету программы бурения, л/с", min_value=1.0, value=28.0, step=0.5)
    
    # Расчет ступеней по регламенту п. 5.1.1.13 (25% и 50%)
    flow_25 = round(target_flow * 0.25, 1)
    flow_50 = round(target_flow * 0.50, 1)
    
    st.markdown("---")
    st.markdown("### 📋 Пошаговая инструкция-задание для машиниста буровых насосов:")
    st.info(f"⚡ **ЭТАП 1 (СТАРТ ТЕСТА):** Запустить циркуляцию строго на расходе **{flow_25} л/с** (25% от плана). Удерживать режим до выравнивания давления на манифольде и полного развоздушивания КНБК.")
    st.info(f"⚡ **ЭТАП 2 (ПЛАВНЫЙ ПОДЪЕМ):** Медленно и непрерывно повышать подачу раствора до уровня **{flow_50} л/с** (50% от плана). Провести оценку пульсаций давления и телеметрии MWD.")
    st.success(f"🍏 **ЭТАП 3 (ВЫВОД НА РЕЖИМ):** При отсутствии замечаний и раскачивания вышки буровой плавно вывести расход на целевые **{target_flow} л/с**.")
