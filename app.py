import streamlit as st
import numpy as np

# Настройка страницы (Формат 16:9, идеален для мобильных телефонов)
st.set_page_config(page_title="Цифровой пульт-помощник инженера", layout="centered")

st.title("📟 Цифровой пульт-помощник бурового инженера")
