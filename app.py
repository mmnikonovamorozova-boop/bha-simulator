import streamlit as st

# Настройка страницы (Широкий формат, как в калькуляторе УМК)
st.set_page_config(page_title="Тренажер инженера ННБ", layout="centered")

st.title("🎓 Интерактивный тренажер осложнений КНБК")
st.caption("Пошаговый калькулятор решений при возникновении внештатных ситуаций на буровой площадке")

# ГЛАВНЫЙ ВЫБОР ИНЦИДЕНТА (Добавлен 3-й пункт)
incident_type = st.radio(
    "⚠️ ВЫБЕРИТЕ ТИП ВОЗНИКШЕГО ОСЛОЖНЕНИЯ:",
    ["Инцидент №1: Резьбовое соединение заклинило на первых витках", 
     "Инцидент №2: Замер осевого люфта ВЗД выше паспортного лимита",
     "Инцидент №3: Обнаружена течь при гидроиспытаниях (опрессовка на поверхности)"]
)

st.markdown("---")

# СЦЕНАРИЙ 1: ЗАКЛИНИВАНИЕ РЕЗЬБЫ
if "Инцидент №1" in incident_type:
    st.subheader("📋 Обязательные первичные действия инженера:")
    st.error("1. Немедленно остановить наживление / вращение инструмента!\n2. Осторожно открутить элемент назад вручную или цепным ключом (без рывков).\n3. Полностью смыть смазку, насухо протереть замок ветошью.")
    
    st.markdown("### 🔍 Проверка факторов и дилемма:")
    defacts = st.selectbox("Есть ли видимые дефекты, задиры или трещины на резьбе?", ["Выбрать...", "Да, обнаружены дефекты", "Нет видимых дефектов"])
    
    if defacts == "Да, обнаружены дефекты":
        clean = st.radio("Глубина задиров допускает локальную зачистку?", ["Да, зачистка возможна", "Нет, повреждения слишком глубокие"])
        
        if clean == "Да, зачистка возможна":
            st.success("🟢 РЕШЕНИЕ: Зачистить заусенцы надфилем/напильником. Проверить вертикальность соосности по СВП. Нанести герметизирующую смазку (2/3 муфта, 1/3 ниппель) и повторно наживить ВРУЧНУЮ.")
            st.info("📊 ВЕРДИКТ: Осложнение ликвидировано. ПРОДОЛЖИТЬ СБОРКУ КНБК.")
        else:
            st.error("🛑 ВЕРДИКТ: ЭЛЕМЕНТ КАТЕГОРИЧЕСКИ ЗАБРАКОВАН! Дальнейшая сборка запрещена.")
            st.warning("⚠️ Обязательные действия: Составить Акт дефекта, незамедлительно уведомить Координатора проекта.")
            
    elif defacts == "Нет видимых дефектов":
        st.success("🟢 РЕШЕНИЕ: Проверить вертикальность и соосность по СВП / талевому блоку. Нанести герметизирующую смазку и повторно наживить элемент ВРУЧНУЮ.")
        st.info("📊 ВЕРДИКТ: Соединение исправно. ПРОДОЛЖИТЬ СБОРКУ КНБК.")

# СЦЕНАРИЙ 2: ПРЕВЫШЕНИЕ ЛЮФТА ВЗД
elif "Инцидент №2" in incident_type:
    st.subheader("📋 Обязательные первичные действия инженера:")
    st.info("1. Выполнить повторный чистый замер по регламентированной формуле:\n   **Люфт = Размер А (на весу) - Размер Б (на столе)**.\n2. Проверить и исключить любые перекосы рулетки при измерениях.")
    
    st.markdown("### 📊 Ввод фактических параметров замера:")
    col1, col2 = st.columns(2)
    with col1:
        size_A = st.number_input("Размер А (на весу), мм", min_value=0.0, value=15.0, step=0.1)
    with col2:
        size_B = st.number_input("Размер Б (на столе ротора), мм", min_value=0.0, value=10.0, step=0.1)
        
    fact_lift = round(size_A - size_B, 2)
    st.metric(label="Фактический расчетный люфт шпинделя (Δh):", value=f"{fact_lift} мм")
    
    passport_limit = st.number_input("Паспортный лимит износа опор по Руководству по эксплуатации, мм", min_value=0.0, value=4.5, step=0.1)
    
    st.markdown("### 🔍 Проверка факторов и дилемма:")
    error_excluded = st.checkbox("Гарантируете, что ошибка измерений на буровой площадке полностью исключена?")
    
    if error_excluded:
        if fact_lift > passport_limit:
            st.error(f"🛑 ВЕРДИКТ: СПУСК В СКВАЖИНУ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕН! Превышен лимит износа подшипников (Фактически {fact_lift} мм > Лимит {passport_limit} мм).")
            st.warning("⚠️ Обязательные действия:\n1. Незамедлительно уведомить Координатора проекта и Заказчика.\n2. Зафиксировать фактические данные износа в Акте входного контроля.\n3. Инициировать экстренную подготовку и завоз резервного ВЗД.")
        else:
            st.success(f"🟢 ВЕРДИКТ: ДВИГАТЕЛЬ ДОПУЩЕН К СКУСКУ. Расчетный люфт {fact_lift} мм находится в пределах паспортной нормы ({passport_limit} мм).")
    else:
        st.warning("📋 РЕКОМЕНДАЦИЯ: Вернитесь на Шаг 1. Перемерить заново, жестко контролируя вертикальность натяжения измерительной рулетки.")

# СЦЕНАРИЙ 3: ОБНАРУЖЕНА ТЕЧЬ ПРИ ГИДРОИСПЫТАНИЯХ (НОВЫЙ БЛОК)
else:
    st.subheader("📋 Обязательные первичные действия инженера:")
    st.error("1. Немедленно дать команду остановить буровые насосы!\n2. Сбросить избыточное давление бурового раствора в манифольде до 0 атм.")
    
    st.markdown("### 🔍 Локализация и анализ неисправности:")
    leak_location = st.selectbox(
        "Где именно локализована течь раствора?",
        ["Выбрать...", "В резьбовом стыке (замок КНБК)", "Из корпуса ВЗД / из узла регулятора угла перекоса"]
    )
    
    if leak_location == "В резьбовом стыке (замок КНБК)":
        under_torque = st.radio("Был ли допущен недотяг соединения по крутящему моменту ключа УМК?", ["Да, момент ниже паспортного", "Нет, момент затяжки в норме"])
        
        if under_torque == "Да, момент ниже паспортного":
            st.success("🟢 РЕШЕНИЕ: Докрепить резьбовое соединение КНБК ключами УМК строго до верхнего паспортного предела.")
            st.info("🔄 СЛЕДУЮЩИЙ ШАГ: Выполнить повторный запуск буровых насосов и провести контроль герметичности.")
        else:
            st.warning("🛠️ РЕШЕНИЕ: Раскрепить замок КНБК машинным ключом. Внимательно проверить торцы и упорные поверхности. Полностью обновить герметизирующую смазку.")
            st.info("🔄 СЛЕДУЮЩИЙ ШАГ: Повторно свинтить соединение, выполнить запуск насосов и контроль герметичности.")
            
    elif leak_location == "Из корпуса ВЗД / из узла регулятора угла перекоса":
        st.error("🛑 ВЕРДИКТ: ДВИГАТЕЛЬ ВЗД КАТЕГОРИЧЕСКИ ЗАБРАКОВАН! Выявлена трещина корпуса или критический износ внутренних уплотнений. Эксплуатация запрещена.")
        st.warning("⚠️ Обязательные действия:\n1. Составить официальный рекламационный акт.\n2. Направить документы Координатору проекта.\n3. Начать экстренную подготовку резервного ВЗД на приемных мостках.")
