        error_excluded = st.checkbox("Исключена ли ошибка измерений и перекосы измерительной рулетки?")
        if error_excluded:
            if fact_lift > passport_limit:
                st.error(f"🛑 ВЕРДИКТ (ЛИМИТ ПРЕВЫШЕН): СПУСК В СКВАЖИНУ ЗАПРЕЩЕН! Износ опор подшипников ВЗД. Оформить Акт износа, экстренно готовить резерв.")
