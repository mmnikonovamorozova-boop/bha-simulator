    radial_angle = math.radians(pull_angle)
    sin_alpha = math.sin(radial_angle)
    loss_percent = round((1.0 - sin_alpha) * 100, 1)
    required_gauge_torque = round(target_torque / sin_alpha, 1)
    
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    if pull_angle == 90:
        st.success(f"🍏 ВЕРДИКТ (ИСХОД ДА): Момент соответствует паспортному. Погрешность 0%. Угол идеален. Выставляйте на моментомере ровно **{target_torque} кН·м**.")
    else:
        st.error(f"📐 Погрешность из-за угла (п. 5.1.1.8), %: {loss_percent}")
        st.success(f"🔗 УСТАНОВИТЬ НА МОМЕНТОМЕРЕ КЛЮЧА, кН·м: {required_gauge_torque}")
        st.warning("🚨 ВЕРДИКТ (ИСХОД НЕТ): Перекос троса! Из-за снижения эффективного плеча силы замок будет недотянут. Тяните до поправки в плашке выше.")

