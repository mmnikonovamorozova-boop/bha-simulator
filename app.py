import streamlit as st
import numpy as np

# Настройка страницы
st.set_page_config(page_title="Инженерный пульт КНБК", layout="centered")

st.title("🎓 Комплексный тренажер рисков КНБК")
st.caption("Единая экспертная система: Сводная матрица рисков, веерные сценарии и инженерные расчеты")

# ЕДИНОЕ МЕНЮ С ТРОЙНЫМ ВЕЕРОМ
mode = st.selectbox(
    "⚠️ ВЫБЕРИТЕ СТРОКУ МАТРИЦЫ ДЛЯ ОТРАБОТКИ СЦЕНАРИЯ:",
    ["Строка 1: Падение давления / Отсутствие пакета данных MWD",
     "Строка 2: Отклонение угла натяжения троса ключа УМК от 90°",
     "Строка 3: Перекос осей резьбы или заклинивание на первых витках",
     "Строка 4: Совпадение частоты пульсаций генератора с частотой вышки",
     "Строка 5: Визуальный контроль КНБК (+ ПОЛНЫЙ ТРОЙНОЙ ВЕЕРНЫЙ СЦЕНАРИЙ)",
     "Строка 6: Резкий вывод насосов буровой на плановый расход раствора"]
)

st.markdown("---")

# =========================================================================
# СТРОКА 1: ТЕСТ ТЕЛЕМЕТРИИ
# =========================================================================
if "Строка 1" in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Нет пакета данных MWD / Падение давления на тесте.\nСледствие: Срыв этапа наземной поверки КНБК на мостках.")
    st.markdown("### 🛠️ Обязательные действия инженера ННБ:")
    st.info("Выполнить контроль уровня сигнала и оборотов генератора. Сделать контрольный поворот КНБК на 90° и 180° для оценки реакции отклонителя. Снять статический замер.")
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    mwd_ok = st.radio("Параметры каротажа стабильны и зенитный угол соответствует глубине опрессовки?", ["Выбрать...", "Да, параметры подтверждены", "Нет, сигналы нестабильны или отсутствуют"])
    
    if mwd_ok == "Да, параметры подтверждены":
        st.success("🍏 ВЕРДИКТ (ИСХОД ДА): СПУСК КНБК В СКВАЖИНУ РАЗРЕШЕН. Параметры в норме.")
    elif mwd_ok == "Нет, сигналы нестабильны или отсутствуют":
        st.error("🚨 ВЕРДИКТ (ИСХОД НЕТ): СТОП ОПЕРАЦИЯ! Подъем телесистемы MWD для ревизии и дефектовки модулей.")

# =========================================================================
# СТРОКА 2: ВАШ ОРИГИНАЛЬНЫЙ КАЛЬКУЛЯТОР КЛЮЧА УМК (ПОЛНОСТЬЮ ВОССТАНОВЛЕН)
# =========================================================================
elif "Строка 2" in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Отклонение угла натяжения троса ключа УМК от 90°.\nСледствие: Скрытый недотяг/перетяг резьбового замка. Риск самоотворота КНБК в скважине.")
    
    st.markdown("### ⚙️ Инженерный калькулятор поправки (п. 5.1.1.8):")
    
    # Исходные параметры из вашего кода
    m_pasport = st.number_input("Паспортный момент затяжки резьбы, кН*м", value=20.0, step=1.0)
    length = st.number_input("Фактическая длина плеча ключа УМК, м", value=1.4, step=0.1)
    angle = st.slider("Угол натяжения троса, градусов", min_value=10, max_value=90, value=80, step=1)
    
    # Расчеты строго по вашему оригинальному алгоритму
    angle_rad = np.radians(angle)
    sin_alpha = np.sin(angle_rad)
    pogreshnost = (1.0 - sin_alpha) * 100
    m_ustavka = m_pasport / sin_alpha
    
    st.markdown("---")
    st.markdown("### 📋 Результаты расчета:")
    
    # Вывод результатов в вашем любимом лаконичном стиле
    st.info(f"📐 Погрешность из-за угла (п. 5.1.1.8), %: {pogreshnost:.1f}")
    st.success(f"🖋️ УСТАНОВИТЬ НА МОМЕНТОМЕРЕ КЛЮЧА, кН*м: {m_ustavka:.1f}")
    st.warning("⚠️ ВНИМАНИЕ: Учтите поправку моментомера! Недокрепление резьбы КНБК ведет к аварии.")

# =========================================================================
# СТРОКА 3: ЗАКЛИНИВАНИЕ РЕЗЬБЫ
# =========================================================================
elif "Строка 3" in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Перекос осей резьбы или заклинивание замка на первых витках при наживлении.\nСледствие: Клиновидный размыв соединения, порча премиального замка КНБК.")
    st.markdown("### 🛠️ Обязательные действия инженера ННБ:")
    st.info("Немедленный стоп свинчивания! Осторожно открутить назад вручную. Полностью смыть смазку, обдуть сжатым воздухом. Осмотреть упорные поверхности.")
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    thread_ok = st.radio("Резьба идет плавно вручную, соосность СВП в норме?", ["Выбрать...", "Да, резьба закручивается плавно", "Нет, соединение по-прежнему клинит"])
    
    if thread_ok == "Да, резьба закручивается плавно":
        st.success("🍏 ВЕРДИКТ (ИСХОД ДА): Нанести смазку (2/3 муфта, 1/3 ниппель). ПРОДОЛЖИТЬ ШТАТНУЮ СБОРКУ КНБК.")
    elif thread_ok == "Нет, соединение по-прежнему клинит":
        st.error("🚨 ВЕРДИКТ (ИСХОД НЕТ): ОТБРАКОВКА переводника/трубы! Составить Акт дефекта, экстренный вызов резерва с мостков.")

# =========================================================================
# СТРОКА 4: РЕЗОНАНС ВЫШКИ
# =========================================================================
elif "Строка 4" in mode:
    st.markdown("### 🔍 Причина и следствие:")
    st.warning("Причина: Совпадение частоты пульсаций генератора импульсов с собственной частотой металлоконструкций буровой.\nСледствие: Резонанс вышки: опасная механическая вибрация, угроза разрушения блоков и верхнего привода СВП.")
    st.markdown("### 🛠️ Обязательные действия инженера ННБ:")
    st.info("Незамедлительно снизить расход буровых насосов до минимума для ослабления импульсов.")
    st.markdown("---")
    st.markdown("### ❓ Развилка (Условие регламента):")
    resonance_stop = st.radio("Опасное раскачивание и вибрация конструкций буровой вышки прекратились?", ["Выбрать...", "Да, вышка стабилизировалась", "Нет, сильное раскачивание продолжается"])
    
    if resonance_stop == "Да, вышка стабилизировалась":
        st.success("🍏 ВЕРДИКТ (ИСХОД ДА): ТЕСТ НА ПОНИЖЕННОМ РАСХОДЕ (Q). Безопасный режим поверки осциллятора на поверхности.")
    elif resonance_stop == "Нет, сильное раскачивание продолжается":
        st.error("🚨 ВЕРДИКТ (ИСХОД НЕТ): СТОП НАСОСОВ! Полный останов теста. Экстренная техническая ревизия вышки и перерасчет параметров подачи.")

# =========================================================================
# СТРОКА 5: ПОЛНЫЙ ТРОЙНОЙ ВЕЕРНЫЙ СЦЕНАРИЙ
# =========================================================================
elif "Строка 5" in mode:
    st.markdown("### 🔍 Базовое правило Строки 5 матрицы рисков:")
    st.info("⚠️ ВНИМАНИЕ: Визуальное отсутствие хода штока генератора на воздухе НЕ является признаком отказа! Амплитуда составляет всего 3-10 мм, ход не обязателен. Исправность на поверхности определяется по приборам давления и MWD.")
    
    st.markdown("---")
    st.markdown("### 🛠️ ПОЛНЫЙ ТРОЙНОЙ ВЕЕРНЫЙ ПАКЕТ ПРОВЕРОК НА ПОВЕРХНОСТИ:")
    sub_incident = st.selectbox(
        "Выберите, какое из трех крыльев веерной матрицы контроля требует анализа:",
        ["Выбрать проверку...", 
         "Крыло 1 (Левое): Анализ заклинивания резьбового соединения на мостках",
         "Крыло 2 (Верхнее): Анализ осевого люфта шпинделя ВЗД перед спуском", 
         "Крыло 3 (Правое): Анализ герметичности (обнаружена течь раствора при опрессовке)"]
    )
    
    # Веер 1: Резьба
    if "Крыло 1" in sub_incident:
        st.markdown("#### 📋 Первичные действия веерного регламента:")
        st.error("❌ СТОП вращение! Открутить элемент назад вручную, полностью смыть смазку, протереть замок замковой части.")
        defacts = st.selectbox("Есть ли видимые дефекты, задиры или трещины на резьбе после очистки?", ["Выбрать...", "Да, обнаружены задиры/дефекты", "Нет видимых дефектов"])
        
        if defacts == "Да, обнаружены задиры/дефекты":
            clean = st.radio("Глубина задиров допускает локальную зачистку надфилем вручную?", ["Выбрать...", "Да, зачистка возможна", "Нет, повреждения слишком глубокие"])
            if clean == "Да, зачистка возможна":
                st.success("🟢 ВЕРДИКТ [ДА]: Зачистить заусенцы надфилем. Смазка 2/3 в муфту. ПРОДОЛЖИТЬ ШТАТНУЮ СБОРКУ КНБК.")
            elif clean == "Нет, повреждения слишком глубокие":
                st.error("🛑 ВЕРДИКТ [НЕТ]: КРИТИЧЕСКИЙ ДЕФЕКТ! ОТБРАКОВКА трубы/переводника. Составить Акт дефекта, вызвать резерв.")
        elif defacts == "Нет видимых дефектов":
            st.success("🟢 ВЕРДИКТ [ДА]: Соосность в норме. ПРОДОЛЖИТЬ СБОРКУ ЭЛЕМЕНТОВ КНБК.")

    # Веер 2: Люфт ВЗД
    elif "Крыло 2" in sub_incident:
        st.markdown("#### 📊 Калькулятор замера осевого люфта:")
        col1, col2 = st.columns(2)
        with col1: size_A = st.number_input("Размер А (на весу), мм", min_value=0.0, value=15.0, step=0.1)
        with col2: size_B = st.number_input("Размер Б (на столе ротора), мм", min_value=0.0, value=10.0, step=0.1)
        
        fact_lift = round(size_A - size_B, 2)
        st.metric(label="Фактический расчетный люфт шпинделя (Δh):", value=f"{fact_lift} мм")
        passport_limit = st.number_input("Паспортный лимит износа опор по Руководству, мм", min_value=0.0, value=4.5, step=0.1)
        
        error_excluded = st.checkbox("Исключена ли ошибка измерений и перекосы измерительной рулетки?")
        if error_excluded:
            if fact_lift > passport_limit:
                st.error(f"🛑 ВЕРДИКТ [ДА]: СПУСК В СКВАЖИНУ ЗАПРЕЩЕН! Износ опор подшипников ВЗД. Оформить Акт износа, готовить резерв.")
            else:
                st.success(f"🟢 ВЕРДИКТ [НЕТ]: ЛЮФТ В НОРМЕ. ДВИГАТЕЛЬ ДОПУЩЕН К СПУСКУ. Зазор {fact_lift} мм в пределах паспорта.")
        else:
            st.warning("⚠️ ПОГРЕШНОСТЬ ЗАМЕРА: Вернитесь на Шаг 1. Перемерить заново, жестко контролируя вертикальность рулетки.")
            
    # Веер 3: Течь раствора
    elif "Крыло 3" in sub_incident:
        st.markdown("#### 📋 Первичные действия веерного регламента:")
        st.error("❌ СТОП насосы буровой! Экстренно сбросить избыточное давление в манифольде до 0 атм.")


