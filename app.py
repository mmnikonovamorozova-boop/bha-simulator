# =========================================================================
if "1.7." in mode:
    st.markdown("### 🛠️ ВЕЕРНЫЙ СЦЕНАРИЙ: ЛОКАЛИЗАЦИЯ ТЕЧИ РАСТВОРА ПРИ ОПРЕССОВКЕ")
    st.error("❌ ПЕРВИЧНОЕ ДЕЙСТВИЕ: СТОП насосы буровой! Сбросить избыточное давление в манифольде до 0 атм.")
    leak_location = st.selectbox("Укажите точное место локализации выхода бурового раствора:", ["Выбрать...", "В резьбовом стыке (замок КНБК - Был недотяг по УМК)", "В резьбовом стыке (замок КНБК - Момент затяжки в норме)", "Из корпуса ВЗД или узла регулятора перекоса"])
    if "Был недотяг" in leak_location:
        st.success("🟢 ВЕРДИКТ: Докрепить соединение ключами УМК строго до верхнего предела. Опрессовать повторно.")
    if "Момент затяжки в норме" in leak_location:
        st.warning("🛠️ ВЕРДИКТ: Раскрепить замок КНБК машинным ключом. Проверить торцы поверхностей, обновить смазку, повторно свинтить.")
    if "Из корпуса ВЗД" in leak_location:
        st.error("🛑 ВЕРДИКТ: ТЕЧЬ ИЗ ТЕЛА -> ДВИГАТЕЛЬ ВЗД КАТЕГОРИЧЕСКИ ЗАБРАКОВАН! Трещина корпуса или критический износ уплотнений. Вызвать резервный ВЗД.")

